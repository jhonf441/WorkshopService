"""
access_plugin_manifest -- the permissions.json of a plugin and the rules it must keep (phase 5 of informes/control-acceso/PLAN-ACCESO.md, section 5
and the corrections of section 10). Pure: no I/O; it reads the tables of permissions.py and permission_caps.py, and the target types of access_targets.

A plugin is NOT a namespace of operations (inventory of phase 0): 18 operations are used by two or more plugins and the shared clients of every plugin
name 23 more. What belongs to a plugin is its SURFACE: opening its page and the pieces of its interface. So a manifest declares:

    {"version": 1,
     "plugin": "WorkshopLights",              the plugin Id (the name of its folder)
     "namespace": "lights",                    its access namespace: [a-z][a-z0-9_]*, the one of "<namespace>:*" and "workshop:<namespace>:..."
     "prefixes": ["light", "lights", "statuslight"],   the first segments of the API operations the plugin OWNS (a prefix has one owner)
     "ui": "ui:lights:open",                   its interface operation (always ui:<namespace>:open)
     "operations": [...],                      every operation of the API the plugin calls (its page, and its own Python server if it has one)
     "shared": [...],                          of those, the ones that are not under its prefixes (another plugin's, or the service's)
     "restricted": [...],                      of those, the ones only an administrator may do (they cannot be delegated, or are not classified)
     "targets": ["lights:scene", ...],         the types of target ("<plugin>:<type>" of access_targets) the plugin's calls work on
     "profiles": {                             the three base profiles of the plugin, built on capabilities (each one holds the lower ones)
        "readonly": {"title": "LightsReadOnly", "capabilities": ["lights.view", "machine.view"]},
        "operator": {"title": "LightsOperator", "capabilities": [...]},
        "admin":    {"title": "LightsAdmin",    "capabilities": [...]}},
     "satellite": "vision_access.py"}          optional: the table of the plugin's own server, which keeps deciding the calls that never reach the API

A plugin may call, without declaring it, the COMMON operations (the clients every plugin shares: session, reserved movement, settings, profile, start-up,
log, heartbeat). Every other operation it calls is under one of its prefixes or is in `shared`. An operation that the API does not know, or that
permissions.OP_ROLES does not classify, is an error (an unclassified operation stays administrator-only, as it always was: nothing here weakens it).

The profiles. `plugin.<namespace>.<level>` are registered in access_base from every valid manifest. Each holds: the interface operation, the COMMON
operations of its level, and the capabilities listed. The level of an operation or a capability is the MORE demanding of two things: the lowest role of its
operations in OP_ROLES (viewer = readonly, operator = operator, technician or administrator = admin) and its class and risk (read and stop = readonly;
write, motion and power of risk 1 or 2 = operator; the rest = admin). Exception: a capability of class read or stop is always readonly (a read that
asks for operator today, like the camera token, asks for it because of privacy; the package of the plugin is the deliberate way to give it). A capability may not sit in a lower profile than its level, and a capability
that cannot be delegated is never in a profile (only the base administrator does those, access_eval). `derive` computes the profiles from the
operations, so a manifest generated by tools/gen_permissions.py of TallerPlugins is the one this module would write.

Findings: {"plugin", "code", "severity": "error" | "info", "detail", "operation"?, "capability"?}. `info` is what the inventory said to expect (an operation
that crosses plugins); only errors make a manifest invalid.
"""
import re

import access_profile
import access_targets
import permission_caps as caps
import permissions

FORMAT_VERSION = 1
LEVELS = ("readonly", "operator", "admin")
TITLE_SUFFIX = {"readonly": "ReadOnly", "operator": "Operator", "admin": "Admin"}
PROFILE_PREFIX = "plugin."
MAX_BYTES = 65536  # a manifest file bigger than this is refused (access_plugin_files)

# The clients every plugin shares (src/_shared and vue/_shared36 of TallerPlugins, inventory 1.2) and the heartbeat of the pages. Sorted. A plugin may
# call them without listing them in `shared`; every profile of a plugin holds the ones of its level that can be delegated.
COMMON_OPERATIONS = (
    "activity.log", "auth.change_pin", "auth.keepalive", "auth.login", "auth.logout", "auth.whoami", "capabilities.get", "examples.create",
    "examples.list", "motion.ask", "motion.release", "motion.renew", "motion.reserve", "motion.take_over", "plugins.stopped.set", "profile.get",
    "profile.set", "readiness.report", "risk.end", "risk.start", "settings.get", "settings.set", "view.heartbeat",
)

_NAMESPACE = re.compile(r"^[a-z][a-z0-9_]{0,31}$")
_PLUGIN = re.compile(r"^[A-Za-z][A-Za-z0-9]{0,63}$")
_PREFIX = re.compile(r"^[a-z][a-z0-9_]{0,31}$")
_OPERATION = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z0-9_]+)+$")
_TARGET = re.compile(r"^[a-z][a-z0-9_]{0,31}:[a-z][a-z0-9_]{0,31}$")
_FIELDS = {"version", "plugin", "namespace", "prefixes", "ui", "operations", "shared", "restricted", "targets", "profiles", "satellite"}
_REQUIRED = _FIELDS - {"satellite"}
_NOT_NAMESPACES = ("cap", "tier", "ui", "base", "plugin", "workshop")
_ROLE_LEVEL = {permissions.VIEWER: 0, permissions.OPERATOR: 1, permissions.TECHNICIAN: 2, permissions.ADMIN: 2}
MAX_OPERATIONS = 300


# ---- levels and capabilities ----

def _class_level(cid):
    c = caps.CAPABILITIES[cid]
    if c["class"] in ("read", "stop"):
        return 0
    if c["class"] == "admin":
        return 2
    return 1 if c["risk"] <= 2 else 2


def _ops_of(cid):
    """The classified operations a capability holds (a pattern of the capability matches the table of roles)."""
    return [op for op in permissions.OP_ROLES if caps.capability_of(op) == cid]


def capability_level(cid):
    """0 readonly, 1 operator, 2 admin: the more demanding of the class and risk of the capability and the lowest role of its operations."""
    if caps.CAPABILITIES[cid]["class"] in ("read", "stop"):
        return 0  # a read (the camera token, the heartbeat) asks for operator today because of privacy, not danger: the package of the plugin is the way to give it
    return max([_class_level(cid)] + [_ROLE_LEVEL[permissions.OP_ROLES[op]] for op in _ops_of(cid)])


def capability_delegable(cid):
    """True when the operations of the capability may be granted by a profile (all of them or none: test_permission_caps)."""
    return all(caps.delegable(op) for op in _ops_of(cid)) and cid in caps.CAPABILITIES and cid != caps.HARDWARE_PARAMS


def operation_level(operation):
    """The level of one operation (see the module doc); 2 when it is not classified."""
    role = permissions.OP_ROLES.get(operation)
    cid = caps.capability_of(operation)
    if role is None or cid is None:
        return 2
    if caps.CAPABILITIES[cid]["class"] in ("read", "stop"):
        return 0
    return max(_ROLE_LEVEL[role], _class_level(cid))


def operation_grantable(operation):
    """True when a profile may grant the operation: it is classified, belongs to a capability and can be delegated."""
    return operation in permissions.OP_ROLES and caps.capability_of(operation) is not None and caps.delegable(operation)


def common_of_level(level):
    """The COMMON operations a profile of `level` (0, 1, 2) holds: the ones that can be granted and are not more demanding than the level."""
    return sorted(op for op in COMMON_OPERATIONS if operation_grantable(op) and operation_level(op) <= level)


# ---- deriving what a manifest holds ----

def prefix_of(operation):
    return str(operation).split(".", 1)[0]


def derive(operations):
    """({"readonly": [...], "operator": [...], "admin": [...]}, restricted): the capabilities of each profile (each holds the lower ones) and the operations
    that only an administrator may do, for the operations a plugin calls (the common ones are left out: every profile holds them)."""
    own = [[], [], []]
    restricted = []
    for op in sorted(set(operations) - set(COMMON_OPERATIONS)):
        cid = caps.capability_of(op) if op in permissions.OP_ROLES else None
        if cid is None or not operation_grantable(op):
            restricted.append(op)
            continue
        if cid not in own[capability_level(cid)] and all(cid not in lst for lst in own):
            own[capability_level(cid)].append(cid)
    readonly = sorted(own[0])
    operator = sorted(set(readonly) | set(own[1]))
    admin = sorted(set(operator) | set(own[2]))
    return {"readonly": readonly, "operator": operator, "admin": admin}, restricted


def title_of(plugin, level):
    """LightsReadOnly for WorkshopLights."""
    base = plugin[len("Workshop"):] if plugin.startswith("Workshop") and len(plugin) > len("Workshop") else plugin
    return base + TITLE_SUFFIX[level]


def profile_id(manifest, level):
    return "%s%s.%s" % (PROFILE_PREFIX, manifest["namespace"], level)


def build_profiles(manifest):
    """{profile id: validated document} of a manifest that has no error. access_profile.ProfileError if the document would not be valid."""
    out = {}
    for i, level in enumerate(LEVELS):
        rules = [{"id": "OpenPlugin", "decision": "allow", "operations": [manifest["ui"]]}]
        common = common_of_level(i)
        if common:
            rules.append({"id": "SharedClients", "decision": "allow", "operations": common})
        held = ["cap:" + c for c in manifest["profiles"][level]["capabilities"]]
        if held:
            rules.append({"id": "Capabilities", "decision": "allow", "operations": held})
        name = profile_id(manifest, level)
        out[name] = access_profile.validate({"version": access_profile.SCHEMA_VERSION, "name": name, "rules": rules})
    return out


def target_type_of(operation):
    """"<plugin>:<type>" of the target the calls of `operation` declare (access_targets.TABLE), or None when it declares none."""
    entry = access_targets.TABLE.get(operation)
    t = access_targets.target_of(operation, {a: "1" for a in entry[0]}) if entry else None
    if not t:
        return None
    plugin, tail = t.split(":", 2)[1:]
    return "%s:%s" % (plugin, tail.split("/", 1)[0])


def known_target_types():
    """{"<plugin>:<type>"} of the targets a call can declare."""
    return {t for t in (target_type_of(op) for op in access_targets.TABLE) if t}


# ---- validation ----

def _f(findings, manifest, code, detail, severity="error", **extra):
    row = {"plugin": str(manifest.get("plugin") if isinstance(manifest, dict) else manifest), "code": code, "severity": severity, "detail": str(detail)}
    row.update(extra)
    findings.append(row)


def _list_of(manifest, key, pattern, findings, limit=MAX_OPERATIONS):
    v = manifest.get(key)
    if not isinstance(v, list) or len(v) > limit or any(not isinstance(x, str) or not pattern.match(x) for x in v) or len(set(v)) != len(v):
        _f(findings, manifest, "invalid_manifest", "%s must be a list of at most %d different names" % (key, limit))
        return None
    return v


def _shape(manifest, findings):
    """Checks the form of the document; returns True when the rest can be checked."""
    if not isinstance(manifest, dict):
        _f(findings, manifest, "invalid_manifest", "the manifest is not an object")
        return False
    extra = set(manifest) - _FIELDS
    missing = _REQUIRED - set(manifest)
    if extra or missing:
        _f(findings, manifest, "invalid_manifest", "unknown fields %s, missing fields %s" % (sorted(extra), sorted(missing)))
        return False
    ok = True
    if isinstance(manifest["version"], bool) or manifest["version"] != FORMAT_VERSION:
        _f(findings, manifest, "invalid_version", "version must be %d" % FORMAT_VERSION)
        ok = False
    if not isinstance(manifest["plugin"], str) or not _PLUGIN.match(manifest["plugin"]):
        _f(findings, manifest, "invalid_manifest", "plugin must be the Id of the plugin")
        ok = False
    ns = manifest["namespace"]
    if not isinstance(ns, str) or not _NAMESPACE.match(ns) or ns in _NOT_NAMESPACES:
        _f(findings, manifest, "invalid_namespace", "the namespace must be lower case letters, digits or _ and cannot be one of %s" % ", ".join(_NOT_NAMESPACES))
        ok = False
    for key, pattern in (("prefixes", _PREFIX), ("operations", _OPERATION), ("shared", _OPERATION), ("restricted", _OPERATION), ("targets", _TARGET)):
        ok = _list_of(manifest, key, pattern, findings) is not None and ok
    if "satellite" in manifest and (not isinstance(manifest["satellite"], str) or not manifest["satellite"].strip()):
        _f(findings, manifest, "invalid_manifest", "satellite must be text")
        ok = False
    pr = manifest["profiles"]
    if not isinstance(pr, dict) or set(pr) != set(LEVELS) or any(not isinstance(pr[k], dict) or set(pr[k]) != {"title", "capabilities"} or
                                                                 not isinstance(pr[k]["title"], str) or not isinstance(pr[k]["capabilities"], list) or
                                                                 any(not isinstance(c, str) for c in pr[k]["capabilities"]) or
                                                                 len(set(pr[k]["capabilities"])) != len(pr[k]["capabilities"])
                                                                 for k in LEVELS if isinstance(pr, dict) and k in pr):
        _f(findings, manifest, "bad_profiles", "profiles must be exactly readonly, operator and admin, each with a title and a list of capabilities")
        ok = False
    return ok


def _check_operations(m, known_ops, findings):
    ns_prefixes, shared, ops = set(m["prefixes"]), set(m["shared"]), m["operations"]
    if m["ui"] != access_profile.ui_operation(m["namespace"]):
        _f(findings, m, "bad_ui", "the interface operation must be %s" % access_profile.ui_operation(m["namespace"]), operation=m["ui"] if isinstance(m["ui"], str) else "")
    for op in ops:
        if op not in known_ops:
            _f(findings, m, "unknown_operation", op, operation=op)
            continue
        if op not in permissions.OP_ROLES:
            _f(findings, m, "unclassified_operation", op, operation=op)
        if prefix_of(op) not in ns_prefixes and op not in shared and op not in COMMON_OPERATIONS:
            _f(findings, m, "outside_namespace", op, operation=op)
    for op in m["shared"]:
        if op not in ops:
            _f(findings, m, "shared_not_called", op, operation=op)
        elif prefix_of(op) in ns_prefixes:
            _f(findings, m, "shared_in_namespace", op, operation=op)
    restricted = set(m["restricted"])
    for op in m["restricted"]:
        if op not in ops:
            _f(findings, m, "restricted_not_called", op, operation=op)
        elif operation_grantable(op):
            _f(findings, m, "restricted_delegable", op, operation=op)


def _check_profiles(m, findings):
    prev, held = set(), []
    for i, level in enumerate(LEVELS):
        p = m["profiles"][level]
        if p["title"] != title_of(m["plugin"], level):
            _f(findings, m, "bad_title", "%s: the title must be %s" % (level, title_of(m["plugin"], level)))
        cur = set(p["capabilities"])
        for cid in sorted(cur):
            if cid not in caps.CAPABILITIES:
                _f(findings, m, "unknown_capability", cid, capability=cid)
            elif not capability_delegable(cid):
                _f(findings, m, "not_delegable_capability", cid, capability=cid)
            elif capability_level(cid) > i:
                _f(findings, m, "level_too_low", "%s in %s needs %s" % (cid, level, LEVELS[capability_level(cid)]), capability=cid)
        if not prev <= cur:
            _f(findings, m, "not_cumulative", "%s lacks %s" % (level, ", ".join(sorted(prev - cur))))
        prev = cur
        held = cur
    covered_by = [cid for cid in held if cid in caps.CAPABILITIES]
    for op in m["operations"]:
        if op in COMMON_OPERATIONS or op in m["restricted"] or op not in permissions.OP_ROLES:
            continue
        if caps.capability_of(op) not in covered_by:
            _f(findings, m, "uncovered_operation", op, operation=op)
    known = known_target_types()
    for t in m["targets"]:
        if t not in known:
            _f(findings, m, "unknown_target", t)


def validate_manifest(manifest, known_ops):
    """The findings of one manifest. `known_ops`: the names of the operations the API registers (the contract)."""
    findings = []
    if not _shape(manifest, findings):
        return findings
    _check_operations(manifest, set(known_ops), findings)
    _check_profiles(manifest, findings)
    return findings


def validate_all(manifests, known_ops):
    """The findings of every manifest ({plugin Id: manifest}) and of the set: a namespace or a prefix with two owners (error), an operation that crosses
    plugins or has no plugin owner (info). Sorted by plugin."""
    findings = []
    shaped = {}
    for pid, m in sorted(manifests.items()):
        mine = validate_manifest(m, known_ops)
        findings.extend(mine)
        if isinstance(m, dict) and not any(f["severity"] == "error" and f["code"] in ("invalid_manifest", "invalid_version", "invalid_namespace", "bad_profiles")
                                           for f in mine):
            shaped[pid] = m
        if isinstance(m, dict) and m.get("plugin") != pid:
            _f(findings, m, "plugin_mismatch", "the manifest of %s names the plugin %r" % (pid, m.get("plugin")))
    owner, ns_owner = {}, {}
    for pid, m in sorted(shaped.items()):
        if m["namespace"] in ns_owner:
            _f(findings, m, "duplicate_namespace", "'%s' is also the namespace of %s" % (m["namespace"], ns_owner[m["namespace"]]))
        ns_owner.setdefault(m["namespace"], pid)
        for p in m["prefixes"]:
            if p in owner:
                _f(findings, m, "duplicate_prefix", "'%s' is also owned by %s" % (p, owner[p]), operation=p)
            owner.setdefault(p, pid)
    for pid, m in sorted(shaped.items()):
        for op in m["shared"]:
            if op in COMMON_OPERATIONS:
                continue
            who = owner.get(prefix_of(op))
            if who is not None and who != pid:
                _f(findings, m, "cross_plugin", "%s belongs to %s" % (op, who), "info", operation=op)
            elif who is None:
                _f(findings, m, "no_owner", "%s is an operation of the service" % op, "info", operation=op)
    return findings


def summary(findings):
    errors = [f for f in findings if f["severity"] == "error"]
    return {"ok": not errors, "errors": len(errors), "info": len(findings) - len(errors)}
