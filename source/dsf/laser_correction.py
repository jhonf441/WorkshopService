"""The laser <-> pointer correction as the board's macros read it. ONE source: the settings store `laser`.

Machine measures the correction (machine.mark_cross, capture with save) and keeps it in the settings store `laser`
(0:/sys/workshop/config/laser.json, key `correction` {x, y, date}); the Workbench and the Jog read it there. The board needs it too: the work
zones 0:/sys/workshop/zones/p<N>.g add it to their origin while global.laserOffsetOn is on, and a zone file used to carry its own copy of the
number, so a new measure changed the store and left the real G54..G59.3 as they were. A G-code macro cannot read JSON, so the service mirrors the
correction into one small macro:

    0:/sys/workshop/macros/lasercorrection.g    set global.workshopLaserCorrX / Y / Known     GENERATED, rewritten whenever the store `laser` changes

workplaces.g, wpload.g and saveworkplace.g declare the three globals (0, 0, false until a correction exists) and run that file before the zones;
each p<N>.g only names the globals (`X{20 + (global.laserOffsetOn ? global.workshopLaserCorrX : 0)}`), never a number. A new correction therefore
rewrites no zone: it is written once here and applied by running wpload.g (below), and laserfocus.g runs wpload.g before every laser job anyway.
`Known` is true only when the store holds a measured correction: with the file missing or Known false the numbers 0 0 are NOT a measure, so
saveworkplace.g refuses to save an origin and the Workbench says so before a cut (a zero correction is a real value only when it was measured).

Writers: settings_store calls sync() after every changed write of `laser` (so the mirror cannot diverge whoever writes the store) and main.py
calls it once at start, then applies the file when the board is free (a machine that already has a correction gets its file after installing
the macros, and the globals in the board's memory take the stored value instead of what they held before). A store that cannot be read (no file,
damaged) is NOT a store without a correction: the file on the card is left as it is and the warning is logged.
"""
import math
import time

import fs_atomic
import machine_gcode
import sd_paths

NAME = "laser"
FILE = "sys/workshop/macros/lasercorrection.g"
LIMIT_MM = 100.0        # a correction beyond this is not a measure (the pointer sits a few cm from the beam): the mirror then says "none" (0 0)


def correction_of(value):
    """(x, y) in mm of the store value `laser`, or None when there is no usable correction (never measured, or not numbers)."""
    c = value.get("correction") if isinstance(value, dict) else None
    if not isinstance(c, dict):
        return None
    x, y = c.get("x"), c.get("y")
    for v in (x, y):
        if isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v) or abs(v) > LIMIT_MM:
            return None
    return float(x), float(y)


def generate_g(corr, date=""):
    """Text of lasercorrection.g. corr = (x, y) or None (no correction: both globals go back to 0)."""
    x, y = corr if corr else (0.0, 0.0)
    measured = ("on " + str(date)[:16] if date else "on an unknown date") if corr else "never"
    return "\n".join([
        "; lasercorrection.g -- laser <-> pointer correction of the machine. GENERATED by WorkshopService from the settings store `laser`",
        "; (Machine > Offsets, measured " + measured + ").",
        "; Do not edit by hand: it is rewritten whenever that store changes. workplaces.g, wpload.g and saveworkplace.g declare the globals and run",
        "; this file; the zones sys/workshop/zones/p<N>.g add them when global.laserOffsetOn is on. Known is false while no correction was measured:",
        "; then 0 0 is not a measure and saveworkplace.g saves no origin.",
        # the file declares what it sets (the macros declare the same globals first; a board whose macros are older than this file, or the other
        # way round, must not stop on "unknown variable": `set` of a global that does not exist aborts the macro that runs it)
        "if !exists(global.workshopLaserCorrX)",
        "    global workshopLaserCorrX = 0",
        "if !exists(global.workshopLaserCorrY)",
        "    global workshopLaserCorrY = 0",
        "if !exists(global.workshopLaserCorrKnown)",
        "    global workshopLaserCorrKnown = false",
        "set global.workshopLaserCorrX = " + machine_gcode.num_text(x),
        "set global.workshopLaserCorrY = " + machine_gcode.num_text(y),
        "set global.workshopLaserCorrKnown = " + ("true" if corr else "false"),
        ""])


def _date_of(value):
    c = value.get("correction") if isinstance(value, dict) else None
    d = c.get("date") if isinstance(c, dict) else ""
    return d if isinstance(d, str) and all(ch.isprintable() and ch not in "\r\n" for ch in d) else ""


def read_text():
    """The file as it is on the card now (None when it does not exist)."""
    try:
        with open(sd_paths.sd(FILE), "rb") as fh:
            return fh.read().decode("utf-8", "replace")
    except OSError:
        return None


_UNSET = object()


def sync(value=_UNSET):
    """Rewrites lasercorrection.g from the store value `laser` (read from the store, under its lock, when not given). True when the file changed.
    - a store that cannot be read (value None: no file, damaged) or is not an object changes NOTHING: it does not say "no correction", it says
      nothing, and writing 0 0 "never" over a measured correction would lose it; the warning is printed;
    - a readable store without a usable correction writes 0 0 and Known false; with no file yet there is nothing to mirror (the globals default
      to 0 and not known): the file is not created."""
    if value is _UNSET:
        import settings_store
        return settings_store.resync(NAME)
    if not isinstance(value, dict):
        print("laser_correction: the store laser cannot be read: lasercorrection.g is left as it is")
        return False
    corr = correction_of(value)
    current = read_text()
    text = generate_g(corr, _date_of(value))
    if current == text or (current is None and corr is None):
        return False
    fs_atomic.write_text(sd_paths.sd(FILE), text)
    return True


def in_step(value=_UNSET):
    """True when the file on the card is exactly what the store `laser` says (a mirror that failed leaves it different): what must hold before
    the board is told to apply it. A store with no correction needs no file to be in step."""
    if value is _UNSET:
        import settings_store
        return settings_store.with_value(NAME, in_step)
    if not isinstance(value, dict):
        return False
    corr = correction_of(value)
    current = read_text()
    if corr is None and current is None:
        return True
    return current == generate_g(corr, _date_of(value))


START_TRIES = 24        # the board may still be starting when the service is: ask for its state this many times ...
START_WAIT_S = 5        # ... this many seconds apart (two minutes in all), then leave it to the next laser job


def apply_at_start(model=None, sleep=time.sleep, tries=START_TRIES, wait_s=START_WAIT_S):
    """Start of the service: runs wpload.g once the board answers and no job is on, so the globals and the zones in the board's memory take the
    stored correction (the board keeps what it had: the file may have been written, or the macros installed, while it kept running). Only when
    the file exists (a machine that never measured one has nothing to apply). -> (applied, reason); a job on the board leaves it to the next
    laser job (laserfocus.g runs wpload.g first)."""
    if read_text() is None:
        return False, "no_file"
    if model is None:
        import machine_ops
        model = machine_ops.model
    om = {}
    for n in range(max(1, tries)):
        om = model() or {}
        if (om.get("state") or {}).get("status"):
            return apply_now(om)
        if n + 1 < tries:
            sleep(wait_s)
    return False, "no_board"


def apply_now(om):
    """Runs wpload.g so the zones take the correction now (G10 L2 only changes numbers in memory, it moves nothing). Not while a job runs: the
    origin must not change under it (laserfocus.g runs wpload.g before the next laser job anyway). -> (applied, reason)."""
    import machine_ops as mo
    return mo.apply_template(om, "work_origins_apply")   # the file is saved: a board that cannot take it now gets it at the next startup or laser job
