import zlib


def tiny_png(w=4, h=3):
    """A valid PNG (w x h, RGB, one colour)."""
    def chunk(kind, data):
        body = kind + data
        return struct.pack(">I", len(data)) + body + struct.pack(">I", zlib.crc32(body) & 0xFFFFFFFF)
    raw = b"".join(b"\x00" + b"\x20\x90\xd0" * w for _ in range(h))
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0)) + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")


def thumbnail_block(w=4, h=3):
    b64 = base64.b64encode(tiny_png(w, h)).decode("ascii")
    lines = ["; thumbnail begin %dx%d %d" % (w, h, len(b64))] + ["; " + b64[i:i + 78] for i in range(0, len(b64), 78)] + ["; thumbnail end"]
    return "\n".join(lines) + "\n"


