def write_big(path, target_bytes, layers_cap=2000):
    """A multi-MB file of circles (relative extrusion, layer markers), written streaming. Returns the number of lines."""
    lines = 0
    with open(path, "w", newline="") as fh:
        fh.write("; generated by PrusaSlicer 2.7.1 on 2026-10-01 at 12:00:00 UTC\nM104 S210\nM140 S60\nM83\n")
        written, layer = 100, 0
        while written < target_bytes and layer < layers_cap:
            head = ";LAYER_CHANGE\n;Z:%.2f\n;HEIGHT:0.2\n;TYPE:Perimeter\n" % (0.2 * (layer + 1))
            body = []
            for ring in range(3):
                r = 10 + ring * 3
                for k in range(300):
                    a = 2 * math.pi * k / 300
                    body.append("G1 X%.3f Y%.3f E%.5f F1800\n" % (100 + r * math.cos(a), 100 + r * math.sin(a), 0.01234))
            text = head + "".join(body)
            fh.write(text)
            written += len(text)
            lines += 4 + len(body)
            layer += 1
        fh.write("; estimated printing time (normal mode) = 10h 0m 0s\n")
    return lines + 5


