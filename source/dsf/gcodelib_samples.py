def _no_comments():
    """No comment at all: the layers come from the Z of the extruding moves (with a z-hop travel before each layer)."""
    out = ["G21\nG90\nM83\n"]
    for i in range(10):
        out.append("G1 Z%.1f F600\nG1 X0 Y0 F6000\n" % (0.2 * (i + 1)))
        out.append(square(0, 0, 10, "E1"))
    return "".join(out)


