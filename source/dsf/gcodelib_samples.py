def _cnc():
    """A router job (Mach3 style): spindle M03 S10000, rapid Z, plunges and two cut depths."""
    out = ["; milling job\nG21\nG90\nG94\nG01 F60.00\nG00 Z2.0000\nM03 S10000\nG04 S3\n"]
    for z in ("-0.1000", "-0.4000"):
        out.append("G00 X5 Y5\nG00 Z0.3000\nG01 Z%s F15.00\nG01 F60.00\nG01 X25 Y5\nG03 X25 Y25 I0 J10\nG01 X5 Y25\nG01 X5 Y5\nG00 Z2.0000\n" % z)
    out.append("M05\nM30\n")
    return "".join(out)


