"""The bed zones settings as the board's macro reads them. ONE source: the settings store `bed-zones` (the service is the brain).

RRF cannot read JSON, so bedzones-set.g (the backup macro of Printing, for when WorkshopService is stopped) loads the numbers it needs from a small
macro the service mirrors from the store, the way focus_geometry.py mirrors the focus rule:

    0:/sys/workshop/config/bedzones.g      GENERATED: the maximum temperature and, per bed, whether it is a zone and its offset

Run with no parameter it sets global.bedZonesMax. Run with B<bed> it also sets global.bedZonesKnown (the bed is listed in the settings),
global.bedZonesActive and global.bedZonesOffset for that bed (a bed that is not listed: not known, not active, offset 0). The macro calls it
once per bed it looks at, so nothing here needs an array (RRF has no nested array literals, and a one element array cannot be written).

Writers: settings_store calls sync() after every changed write of `bed-zones`, so the two cannot diverge whoever writes the store; at start the
service writes it again (sync_at_start). The file is never edited by hand and carries no decision of its own: what the macro refuses (a
temperature over the maximum) is what the service refuses. A store that is missing, cannot be read or is not valid leaves the file on the card
as it is: the last valid copy, which is also what the macro falls back to when there is no file at all (its own default maximum).
"""
import bed_zones_config
import fs_atomic
import machine_gcode
import sd_paths

NAME = "bed-zones"
FILE = "sys/workshop/config/bedzones.g"


def config_of(value):
    """The validated configuration of the store value, or None when there is none or it is not valid (the file is then left alone)."""
    if not isinstance(value, dict):
        return None  # no store, or something that is not a settings object (a list, a number): not a copy to trust
    try:
        return bed_zones_config.validate(value)
    except bed_zones_config.ConfigError:
        return None


def generate_g(config):
    """Text of bedzones.g for a validated configuration. One block per listed bed, in the order of the settings."""
    num = machine_gcode.num_text
    lines = [
        "; bedzones.g -- the Bed zones settings in the form RRF can read (RRF cannot read bed-zones.json). bedzones-set.g loads this file.",
        "; GENERATED by WorkshopService from the settings store `bed-zones` (0:/sys/workshop/config/bed-zones.json): it is rewritten whenever that",
        "; store changes. Do not edit it: change the settings in the Bed zones section of Printing.",
        "; No parameter: sets global.bedZonesMax. With B<bed>: also global.bedZonesKnown / bedZonesActive / bedZonesOffset of that bed.",
        "if !exists(global.bedZonesMax)",
        "    global bedZonesMax = " + num(config["max_temp"]),
        "if !exists(global.bedZonesKnown)",
        "    global bedZonesKnown = false",
        "if !exists(global.bedZonesActive)",
        "    global bedZonesActive = false",
        "if !exists(global.bedZonesOffset)",
        "    global bedZonesOffset = 0",
        "set global.bedZonesMax = " + num(config["max_temp"]),
        "set global.bedZonesKnown = false",
        "set global.bedZonesActive = false",
        "set global.bedZonesOffset = 0",
        "if exists(param.B)",
    ]
    first = True
    for zone in config["zones"]:
        lines.append("    %s param.B == %d" % ("if" if first else "elif", zone["bed"]))
        lines.append("        set global.bedZonesKnown = true")
        lines.append("        set global.bedZonesActive = " + ("true" if zone["active"] else "false"))
        lines.append("        set global.bedZonesOffset = " + num(zone["offset"]))
        first = False
    lines.append("")
    return "\n".join(lines)


def read_text():
    """The file as it is on the card now (None when it does not exist)."""
    try:
        with open(sd_paths.sd(FILE), "rb") as fh:
            return fh.read().decode("utf-8", "replace")
    except OSError:
        return None


_UNSET = object()


def sync(value=_UNSET):
    """Rewrites bedzones.g from the store value `bed-zones` (read from the store, under its lock, when not given). True when the file changed.
    A store that is missing or not valid changes nothing (the file on the card stays) and the reason is printed."""
    if value is _UNSET:
        import settings_store
        return settings_store.resync(NAME)
    config = config_of(value)
    if config is None:
        print("bed_zones_mirror: the store bed-zones is missing or not valid: bedzones.g is left as it is")
        return False
    text = generate_g(config)
    if read_text() == text:
        return False
    fs_atomic.write_text(sd_paths.sd(FILE), text)
    return True


def sync_at_start():
    """Service start: writes bedzones.g from the store when it differs (the store is the only source, nobody tunes this file by hand).
    -> "written" | "present" | "no_config"."""
    import settings_store
    return settings_store.with_value(NAME, _at_start)


def _at_start(value):
    config = config_of(value)
    if config is None:
        return "no_config"
    text = generate_g(config)
    if read_text() == text:
        return "present"
    fs_atomic.write_text(sd_paths.sd(FILE), text)
    return "written"
