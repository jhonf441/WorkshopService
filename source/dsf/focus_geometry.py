"""The geometry of the laser focus rule as the board's macros read it. ONE source: the settings store `focus`.

The Workbench works out the focus height of a material from the two numbers of 0:/sys/workshop/config/focus.json (key `geometry`:
`focusBelowBoxEdge` and `boxEdgeAboveReference`, measured with focusref.g). A G-code macro cannot read JSON, so focusrule.g loads the same two
numbers from a small macro the service mirrors from the store (the way laser_correction.py mirrors the laser correction):

    0:/sys/workshop/config/focus.g      declare and set global.focusTab / global.focusBoxEdge      GENERATED

Writers: settings_store calls sync() after every changed write of `focus`, so the two files cannot diverge whoever writes the store. At start
the service only creates focus.g when it is MISSING (sync_at_start): a focus.g that exists and says other numbers may have been tuned by hand
before this mirror existed, so it is never overwritten behind the owner's back; the Workbench keeps warning ("differs") until the store is saved
once, which rewrites the file. A store that cannot be read, or whose numbers are absurd, leaves the file on the card as it is.
"""
import math
import re

import fs_atomic
import machine_gcode
import sd_paths

NAME = "focus"
FILE = "sys/workshop/config/focus.g"
TAB_MAX_MM = 30.0       # the same limits the page applies to focus.json (tzFocusGeoOfJson): tab in (0, 30], edge in [-5, 5]
EDGE_MAX_MM = 5.0


def geometry_of(value):
    """(tab, edge) in mm of the store value `focus`, or None when a number is missing or absurd."""
    g = value.get("geometry") if isinstance(value, dict) else None
    if not isinstance(g, dict):
        return None
    tab, edge = g.get("focusBelowBoxEdge"), g.get("boxEdgeAboveReference")
    for v in (tab, edge):
        if isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v):
            return None
    if not 0 < tab <= TAB_MAX_MM or abs(edge) > EDGE_MAX_MM:
        return None
    return float(tab), float(edge)


def generate_g(geo):
    """Text of focus.g for geo = (tab, edge). The lines `set global.focusTab = N` are what the Workbench reads back (tzFocusGeoOfG)."""
    tab, edge = (machine_gcode.num_text(v) for v in geo)
    return "\n".join([
        "; focus.g -- the two numbers of the focus rule in the form RRF can read (RRF cannot read focus.json). focusrule.g loads this file.",
        "; GENERATED by WorkshopService from the settings store `focus` (0:/sys/workshop/config/focus.json, geometry.focusBelowBoxEdge and",
        "; geometry.boxEdgeAboveReference): it is rewritten whenever that store changes. Measure yours with focusref.g.",
        "if !exists(global.focusTab)",
        "    global focusTab = " + tab,
        "if !exists(global.focusBoxEdge)",
        "    global focusBoxEdge = " + edge,
        "set global.focusTab = " + tab + "                       ; focusBelowBoxEdge: mm the focus is under the edge of the lens box with the tab (lever 0)",
        "set global.focusBoxEdge = " + edge + "                 ; boxEdgeAboveReference: mm the edge of the box is above the reference the probe measures",
        ""])


def read_text():
    """The file as it is on the card now (None when it does not exist)."""
    try:
        with open(sd_paths.sd(FILE), "rb") as fh:
            return fh.read().decode("utf-8", "replace")
    except OSError:
        return None


_UNSET = object()


def sync(value=_UNSET):
    """Rewrites focus.g from the store value `focus` (read from the store, under its lock, when not given). True when the file changed. A store
    that cannot be read or has no valid geometry changes nothing (the file on the card stays) and the reason is printed."""
    if value is _UNSET:
        import settings_store
        return settings_store.resync(NAME)
    geo = geometry_of(value)
    if geo is None:
        print("focus_geometry: the store focus has no usable geometry (unreadable, missing or absurd numbers): focus.g is left as it is")
        return False
    text = generate_g(geo)
    if read_text() == text:
        return False
    fs_atomic.write_text(sd_paths.sd(FILE), text)
    return True


def sync_at_start():
    """Service start: creates focus.g from the store when the file is missing (under the lock of the store, like every mirror). Never replaces
    one that exists (it may be hand-tuned); says so when it differs. -> "written" | "present" | "differs" | "no_geometry"."""
    import settings_store
    return settings_store.with_value(NAME, _at_start)


def _at_start(value):
    current = read_text()
    geo = geometry_of(value)
    if geo is None:
        return "no_geometry"
    if current is None:
        fs_atomic.write_text(sd_paths.sd(FILE), generate_g(geo))
        return "written"
    return "present" if current == generate_g(geo) or _numbers_of(current) == geo else "differs"


def _numbers_of(text):
    tab = re.search(r"^[ \t]*set[ \t]+global\.focusTab[ \t]*=[ \t]*(-?\d+(?:\.\d+)?)", text, re.M)
    edge = re.search(r"^[ \t]*set[ \t]+global\.focusBoxEdge[ \t]*=[ \t]*(-?\d+(?:\.\d+)?)", text, re.M)
    return (float(tab.group(1)), float(edge.group(1))) if tab and edge else None

