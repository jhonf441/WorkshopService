"""Streaming parser of one G-code file for the library (PURE: it reads the lines it is given, never opens a file, never writes).

    parse_stream(lines, on_layer=None, on_chunk=None, chunk_lines=4000, tol=0.05) -> result
    Parser(on_layer, tol).feed(raw_line_bytes) ... .finish() -> result

`lines` is any iterable of bytes (or str) lines; the parser keeps ONE line at a time and the geometry of ONE layer (a layer is handed to
`on_layer(info, segs, travel)` as soon as it closes, the caller stores it), so a multi-MB file never sits in memory.
`on_chunk(lines_done)` is called every `chunk_lines` lines: the indexer throttles and checks for a stop there (it may raise to abort).

What it reads (all optional, whatever the slicer wrote):
  - slicer name and version ("generated by PrusaSlicer 2.7.1", "Generated with Cura_SteamEngine 5.3.0", OrcaSlicer, SuperSlicer, ...);
  - estimated time of the slicer (PrusaSlicer / Orca "estimated printing time (normal mode) = 1h 2m 3s", "total estimated time:", Cura ";TIME:3724");
  - filament used (mm, cm3, g, cost), layer heights, nozzle diameter from the config comments of the header or the footer;
  - thumbnails ("; thumbnail begin 220x124 5432" ... "; thumbnail end", base64 PNG, PrusaSlicer / OrcaSlicer / Cura style);
  - feature types (";TYPE:" / "; FEATURE:"), the object name, every other "; key = value" comment (header dict, capped);
  - layers: ";LAYER_CHANGE" + ";Z:" + ";HEIGHT:" (Prusa / Orca), "; CHANGE_LAYER" + "; Z_HEIGHT:" (Orca), ";LAYER:n" (Cura); a file without
    markers falls back to the Z of the extruding moves;
  - the path of every layer per feature type (G0/G1 and G2/G3 arcs, absolute or relative XYZ and E), simplified while it is read.
Files that are not prints (laser, cnc, travel: see gcodelib_kind.py) get 2D layers (`layers[].name`, z may be None) and `plane` "2d"; the
summary always has `kind`, `plane` and `tags`. `name` (file name) lets a .nc / .ngc / .tap extension count as evidence.
The result is {"summary", "header", "layers": [info], "types", "thumbs": [(w, h, png bytes)], "plane"}; the summary has no file size / mtime
(the caller adds them). Time per layer is a rough kinematic estimate (distance / feed, no acceleration).
"""
import base64
import math
import re
from array import array

import gcode_plan
import gcodelib_geo as geo
import gcodelib_kind as kind_mod

MAX_HEADER = 400
VALUE_CHARS = 200
MAX_TYPES = 24
MAX_THUMBS = 4
MAX_THUMB_CHARS = 400000
HELD_LAYERS = 6          # layers seen before the first marker are held: a marker may turn them into a preamble
MAX_LAYERS = 20000
MIN_TRAVEL_MM = 2.0
MAX_TRAVEL_FLOATS = 6000  # per layer (4 floats per move)
SKIP_KEYS = {"type", "layer", "z", "height", "width", "mesh", "time_elapsed", "feature", "layer_change", "before_layer_change", "after_layer_change"}

_KEY = re.compile(r"^;\s*([A-Za-z_][\w ()\[\]%/.\-]{0,70}?)\s*[=:]\s*(.*)$")
_GEN = re.compile(r"generated\s+(?:by|with)\s+(.+?)(?:\s+(?:v|version\s*)?(\d+(?:\.\d+)+\S*))?(?:\s+on\s+\d.*)?$", re.I)
_DUR = re.compile(r"(\d+(?:\.\d+)?)\s*([dhms])")
_NUM = re.compile(r"[-+]?\d+(?:\.\d+)?")
_THUMB = re.compile(r"^;\s*thumbnail(_\w+)?\s+begin\s+(\d+)\s*x\s*(\d+)\s+(\d+)", re.I)
_PARAM = re.compile(rb"([XYZEFIJRSxyzefijrs])\s*(-?\d*\.?\d+)")
_KEYS = {k: k.decode().upper() for k in map(bytes, ([c] for c in b"XYZEFIJRSxyzefijrs"))}
_MULTI = re.compile(rb"\s[GgMm]\d")  # more than one command on a line ("G90 M5 G0 X1 Y2")
_SPLIT = re.compile(rb"(?:^|\s)[GgMm]\d+(?:\.\d+)?(?=\s|$|[A-Za-z])")
_STRING_CMDS = (b"M98", b"M11", b"M32", b"M23")  # their argument is a text: never split
_SPINDLE = (b"M3", b"M03", b"M4", b"M04", b"M5", b"M05")
_MOVES = {b"G0": 0, b"G00": 0, b"G1": 0, b"G01": 0, b"G2": 2, b"G02": 2, b"G3": 3, b"G03": 3}
_PNG = b"\x89PNG\r\n\x1a\n"


def duration_s(text):
    """Seconds of "1d 2h 3m 4s" / "1h 2m" / "45s" (None when there is no unit)."""
    found = _DUR.findall(text or "")
    if not found:
        return None
    mult = {"d": 86400, "h": 3600, "m": 60, "s": 1}
    return int(round(sum(float(n) * mult[u] for n, u in found)))


def numbers(text):
    return [float(x) for x in _NUM.findall(text or "")]


def _f(token):
    try:
        return float(token)
    except ValueError:
        return None


class Parser:
    def __init__(self, on_layer=None, tol=0.05, name=None):
        self.on_layer = on_layer or (lambda info, segs, travel: None)
        self.tol = tol
        self.n = 0
        self.header, self.lower = {}, {}
        self.slicer = self.object_name = None
        self.thumbs, self._thumb = [], None
        self.types, self._tindex = [], {}
        self.pos = {"x": 0.0, "y": 0.0, "z": 0.0, "e": 0.0}
        self.rel_xyz = self.rel_e = False
        self.feed = 1800.0
        self.cur_type = None  # the feature of the moves; "Unknown" is created the first time a move is drawn without a ;TYPE:
        self.bbox = None  # [x0, y0, x1, y1]
        self.layers, self.marker, self.locked, self._held = [], False, False, []
        self.layer = None
        self.poly = geo.PolyBuilder(tol)
        self.drawing = False
        self.flat = kind_mod.Flat(tol, name)  # kind of file and the 2D toolpath of the files that are not prints
        self.kind, self.plane = None, "3d"

    # ---- layers ----
    def _new_layer_state(self, z, height=None):
        return {"z": z, "height": height, "t": 0.0, "types": set(), "segs": {}, "travel": array("f")}

    def _cur(self):
        if self.cur_type is None:
            self.cur_type = self._type_index("Unknown")
        return self.cur_type

    def _close_poly(self):
        if not self.drawing:
            return
        self.drawing = False
        arr = self.poly.close()
        if arr is not None and self.layer is not None:
            self.layer["segs"].setdefault(self.cur_type, []).append(arr)
            self.layer["types"].add(self.cur_type)

    def _close_layer(self):
        self._close_poly()
        lay = self.layer
        self.layer = None
        if lay is None or (not lay["segs"] and lay["t"] == 0.0):
            return
        prev = self.layers[-1]["z"] if self.layers else 0.0
        z = lay["z"] if lay["z"] is not None else prev
        h = lay["height"] if lay["height"] else round(max(0.0, z - prev), 4)
        info = {"layer": len(self.layers), "z": round(z, 4), "height": round(h, 4),
                "est_time_s": round(lay["t"], 1), "features": sorted(self.types[t] for t in lay["types"])}
        self.layers.append(info)
        if self.marker or self.locked:
            self.on_layer(info, lay["segs"], lay["travel"])
        else:
            self._held.append((info, lay["segs"], lay["travel"]))
            if len(self._held) > HELD_LAYERS:
                self.locked = True  # no marker so far: the Z of the moves decides, from now on
                for held in self._held:
                    self.on_layer(*held)
                self._held = []

    def _start_layer(self, z, height=None):
        self._close_layer()
        self.layer = self._new_layer_state(z, height)
        self.drawing = False

    def _marker(self, z=None, height=None):
        if self.locked:
            return
        if not self.marker:
            self.marker = True
            self.layers, self._held = [], []  # whatever came before the first marker is the preamble (purge line...)
            self.layer = None
            self.drawing = False
        self._start_layer(z, height)

    # ---- comments ----
    def _type_index(self, name):
        name = name.strip()[:40] or "Unknown"
        if name not in self._tindex:
            if len(self.types) >= MAX_TYPES:
                name = "Other"
            if name not in self._tindex:
                self._tindex[name] = len(self.types)
                self.types.append(name)
        return self._tindex[name]

    def _thumb_line(self, text):
        t = self._thumb
        if re.match(r"^;\s*thumbnail(?:_\w+)?\s+end", text, re.I):
            self._thumb = None
            if t["png"] and len(self.thumbs) < MAX_THUMBS:
                try:
                    data = base64.b64decode("".join(t["parts"]), validate=False)
                except ValueError:
                    return
                if data.startswith(_PNG):
                    self.thumbs.append((t["w"], t["h"], data))
            return
        t["chars"] += len(text)
        if t["png"]:
            t["parts"].append(text.lstrip("; \t").strip())
        if t["chars"] > MAX_THUMB_CHARS:
            self._thumb = None

    def _comment(self, raw):
        text = raw.decode("utf-8", "replace").rstrip("\r\n")
        if self._thumb is not None:
            return self._thumb_line(text)
        m = _THUMB.match(text)
        if m:
            self._thumb = {"w": int(m.group(2)), "h": int(m.group(3)), "parts": [], "chars": 0, "png": (m.group(1) or "_png").lower() == "_png"}
            return
        body = text[1:].strip()
        low = body.lower()
        if self.flat.active:
            self.flat.comment(body, low)
        if low in ("layer_change", "change_layer"):
            return self._marker()
        if low.startswith("type:") or low.startswith("feature:"):
            self._close_poly()
            self.cur_type = self._type_index(body.split(":", 1)[1])
            return
        self._comment_value(text, body, low)

    def _comment_value(self, text, body, low):
        if low.startswith("layer:") and not self.locked:
            return self._marker() if _f(body[6:].strip()) is not None else None
        if self.marker and self.layer is not None:
            for key, attr in (("z:", "z"), ("z_height:", "z"), ("height:", "height"), ("layer_height:", "height")):
                v = _f(body[len(key):].strip()) if low.startswith(key) else None
                if v is not None:
                    self.layer[attr] = v
                    return
        if self.slicer is None and "generated" in low:
            self._slicer(body)
        if "estimated time" in low:
            m = re.search(r"total estimated time:\s*([^;]+)", body, re.I)
            if m:
                self.lower.setdefault("total estimated time", m.group(1).strip())
        if low.startswith("printing object ") and self.object_name is None:
            self.object_name = re.sub(r"\s+id:\d+.*$", "", body[len("printing object "):]).strip()[:80] or None
        elif low.startswith("mesh:") and self.object_name is None and not low.startswith("mesh:nonmesh"):
            self.object_name = body[5:].strip()[:80] or None
        if not low.startswith("generated"):
            self._header(text)

    def _slicer(self, body):
        m = _GEN.search(body)
        if m:
            self.slicer = {"name": m.group(1).strip().rstrip("(R)").strip()[:60], "version": m.group(2)}

    def _header(self, text):
        m = _KEY.match(text)
        if not m:
            return
        key, value = m.group(1).strip(), m.group(2).strip()
        low = key.lower()
        if low in SKIP_KEYS or low in self.lower or len(self.header) >= MAX_HEADER:
            return
        self.header[key] = value[:VALUE_CHARS]
        self.lower[low] = value[:VALUE_CHARS]

    # ---- moves ----
    def _extrude_point(self, x, y, z):
        lay = self.layer
        if lay is None:
            if self.marker:
                return
            self._start_layer(z)
            lay = self.layer
        elif not self.marker and lay["z"] is not None and abs(z - lay["z"]) > 0.001 and len(self.layers) < MAX_LAYERS:
            self._start_layer(z)
            lay = self.layer
        if lay["z"] is None:
            lay["z"] = z
        b = self.bbox
        if b is None:
            self.bbox = [x, y, x, y]
        else:
            if x < b[0]:
                b[0] = x
            elif x > b[2]:
                b[2] = x
            if y < b[1]:
                b[1] = y
            elif y > b[3]:
                b[3] = y
        px, py = self.pos["x"], self.pos["y"]
        if not self.drawing:
            self.poly.start(px, py)
            self.drawing = True
        self.poly.add(x, y)
        lay["types"].add(self._cur())

    def _travel(self, x0, y0, x1, y1):
        lay = self.layer
        if lay is None or len(lay["travel"]) >= MAX_TRAVEL_FLOATS or math.hypot(x1 - x0, y1 - y0) < MIN_TRAVEL_MM:
            return
        lay["travel"].extend((x0, y0, x1, y1))

    def _step(self, x, y, z, extruding):
        """One straight piece from the current position to (x, y, z)."""
        p = self.pos
        if self.flat.active:
            self.flat.step(p["x"], p["y"], p["z"], x, y, z, self.feed)
        dist = math.sqrt((x - p["x"]) ** 2 + (y - p["y"]) ** 2 + (z - p["z"]) ** 2)
        if self.layer is not None and self.feed > 0:
            self.layer["t"] += dist / (self.feed / 60.0)
        if extruding:
            self._extrude_point(x, y, z)
        elif x != p["x"] or y != p["y"]:
            self._close_poly()
            self._travel(p["x"], p["y"], x, y)
        p["x"], p["y"], p["z"] = x, y, z

    def _move(self, args, arc, g0=False):
        p = self.pos
        if self.flat.active:
            self.flat.begin_move(g0, args)
        if "F" in args and args["F"] > 0:
            self.feed = args["F"]
        nx = p["x"] + args["X"] if self.rel_xyz and "X" in args else args.get("X", p["x"])
        ny = p["y"] + args["Y"] if self.rel_xyz and "Y" in args else args.get("Y", p["y"])
        nz = p["z"] + args["Z"] if self.rel_xyz and "Z" in args else args.get("Z", p["z"])
        de = 0.0
        if "E" in args:
            de = args["E"] if self.rel_e else args["E"] - p["e"]
            p["e"] = p["e"] + args["E"] if self.rel_e else args["E"]
        extruding = de > 1e-9 and (nx != p["x"] or ny != p["y"] or (arc and ("I" in args or "J" in args)))  # a full circle ends where it began
        if extruding:
            self.flat.note_extrude()
        if arc and (nx != p["x"] or ny != p["y"] or "I" in args or "J" in args):
            pts = gcode_plan._arc({"X": p["x"], "Y": p["y"]}, {"X": nx, "Y": ny}, args, arc == 2, 1.0)
            n = len(pts)
            z0 = p["z"]
            for i, (ax, ay) in enumerate(pts, 1):
                self._step(ax, ay, z0 + (nz - z0) * i / n, extruding)
            return
        self._step(nx, ny, nz, extruding)

    def _code(self, raw):
        cut = raw.find(b";")
        if cut >= 0:
            raw = raw[:cut]
        if _MULTI.search(raw) and raw.lstrip()[:3].upper() not in _STRING_CMDS:
            starts = [m.start() for m in _SPLIT.finditer(raw)]
            if len(starts) > 1:
                for a, b in zip(starts, starts[1:] + [len(raw)]):
                    self._code_one(raw[a:b])
                return
        self._code_one(raw)

    def _code_one(self, raw):
        parts = raw.split(None, 1) if raw[:2] in (b"G0", b"G1", b"G2", b"G3") else raw.split()
        if parts and parts[0][:1] in (b"N", b"n") and len(parts[0]) > 1 and parts[0][1:].isdigit():
            parts = parts[1:]
        if not parts:
            return
        word = parts[0].upper()
        if word in _MOVES:
            args = {_KEYS[k]: float(v) for k, v in _PARAM.findall(raw)}
            self._move(args, _MOVES[word], word in (b"G0", b"G00"))
        elif word == b"G90":
            self.rel_xyz = False
        elif word == b"G91":
            self.rel_xyz = True
        elif word == b"M82":
            self.rel_e = False
        elif word == b"M83":
            self.rel_e = True
        elif word in _SPINDLE:
            self.flat.spindle(word, raw)
        elif word == b"M98" or word == b"M118":
            self.flat.note_code(word, raw)
        elif word == b"G92":
            for tok in parts[1:]:
                k, v = tok[:1].decode("ascii", "ignore").lower(), _f(tok[1:]) if len(tok) > 1 else None
                if k in self.pos and v is not None:
                    self.pos[k] = v

    def feed_line(self, raw):
        if isinstance(raw, str):
            raw = raw.encode("utf-8", "replace")
        self.n += 1
        c = raw[:1]
        if c == b";":
            self._comment(raw)
        elif c in (b"G", b"N", b"g", b"M", b"m", b" ", b"\t"):
            self._code(raw)

    def finish(self):
        self._close_layer()
        if not self.marker and not self.locked:
            for held in self._held:
                self.on_layer(*held)
            self._held = []
        self.kind = self.flat.decide(bool(self.layers))
        types, infos = list(self.types), None
        if self.kind != "fff":
            self.plane = "2d"
            self.flat.finish()
            types = self.flat.type_names()
            infos = self.flat.deliver(self.on_layer)
            self.layers = infos
        summary = build_summary(self, infos)
        return {"summary": summary, "header": self.header, "layers": self.layers, "types": types, "thumbs": self.thumbs, "plane": self.plane}


def _first(lower, *keys):
    for k in keys:
        if k in lower:
            n = numbers(lower[k])
            if n:
                return n
    return None


def build_summary(p, infos=None):
    """The summary dict: only what the file said (or what its geometry gives), nothing invented."""
    if infos is not None:
        return kind_mod.flat_summary(p.flat, p.kind, p, infos)
    lw = p.lower
    s = {"kind": "fff", "plane": "3d"}
    if p.slicer:
        s["slicer"] = p.slicer["name"]
        if p.slicer["version"]:
            s["slicer_version"] = p.slicer["version"]
    s["layers"] = len(p.layers)
    z = [layer["z"] for layer in p.layers]
    h = _first(lw, "layer_height", "layer height")
    s["layer_height"] = h[0] if h else (p.layers[1]["z"] - p.layers[0]["z"] if len(p.layers) > 1 else None)
    f = _first(lw, "first_layer_height", "initial_layer_print_height", "initial layer height")
    s["first_layer_height"] = f[0] if f else (p.layers[0]["z"] if p.layers else None)
    t = None
    for key in ("estimated printing time (normal mode)", "total estimated time", "estimated printing time", "estimated time"):
        if key in lw and duration_s(lw[key]) is not None:
            t = duration_s(lw[key])
            break
    if t is None and "time" in lw and re.fullmatch(r"\d+", lw["time"].strip()):
        t = int(lw["time"])  # Cura ;TIME:3724
    s["time_s"] = t
    s["time_calc_s"] = int(round(sum(layer["est_time_s"] for layer in p.layers))) or None
    s["filament_mm"] = _sum(lw, "filament used [mm]", "total filament used [mm]")
    if s["filament_mm"] is None and "filament used" in lw:  # Cura: "1.234m"
        n = numbers(lw["filament used"])
        if n:
            s["filament_mm"] = round(n[0] * (1000.0 if lw["filament used"].strip().lower().endswith("m") and "mm" not in lw["filament used"] else 1.0), 1)
    s["filament_cm3"] = _sum(lw, "filament used [cm3]", "total filament used [cm3]")
    s["filament_g"] = _sum(lw, "total filament used [g]", "filament used [g]")
    s["filament_cost"] = _sum(lw, "total filament cost", "filament cost")
    nz = _first(lw, "nozzle_diameter")
    s["nozzle_mm"] = nz[0] if nz else None
    s["bbox"] = {"min": [round(p.bbox[0], 2), round(p.bbox[1], 2), round(min(z), 3) if z else 0.0],
                 "max": [round(p.bbox[2], 2), round(p.bbox[3], 2), round(max(z), 3) if z else 0.0]} if p.bbox else None
    s["features"] = list(p.types) if p.layers else []
    s["has_thumbnail"] = bool(p.thumbs)
    s["object"] = p.object_name
    s["tags"] = p.flat.tags("fff", p.slicer["name"] if p.slicer else None, bool(p.thumbs))
    return {k: v for k, v in s.items() if v is not None and v != []}


def _sum(lower, *keys):
    n = _first(lower, *keys)
    return round(sum(n), 3) if n else None


def parse_stream(lines, on_layer=None, on_chunk=None, chunk_lines=4000, tol=0.05, name=None):
    p = Parser(on_layer, tol, name)
    feed = p.feed_line
    count = 0
    for raw in lines:
        feed(raw)
        count += 1
        if count % chunk_lines == 0 and on_chunk is not None:
            on_chunk(count)
    out = p.finish()
    out["lines"] = count
    return out
