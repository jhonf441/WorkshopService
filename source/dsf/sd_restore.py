"""
sd_restore -- restores ONE workshop-owned file of the SD from the factory copy, only when an administrator asks for exactly that
file (SD-LAYOUT.md F.1 phase 6, F.3, F.5, decision G9). It is never automatic and never silent.

Two steps, both per file:
  preview(path)                          writes NOTHING: the state, the refusals (if any), the unified diff current -> factory and the
                                         sha of the current file that the person is looking at (expected_sha)
  restore(path, expected_sha, ...)       does it, but only if the file is still the one the preview showed

Refused with a clear code (never restored by this module):
  not_in_manifest, wrong_kind (template: the person's after the first copy; native-managed: the person's; generated: the service
  rewrites it; expected-external: nobody ships it), safety (anything that runs in pause, cancel, homing, the laser guard or at start-up:
  it changes only with the owner at the machine, phases 3 to 5 of F.1), already_ok, factory_missing / factory_mismatch (no trustworthy
  copy), not_a_file, board_busy (the board is not idle).

Before the file is replaced the current one is copied to sys/workshop/legacy/<YYYYMMDD>/<path>; the new bytes go in through
fs_atomic (temporary file, fsync, os.replace); the result is checked by sha; the action goes to install_actions (trigger
integrity-restore) with sha before and after. The factory tree is `dsf/factory/<path>` next to this module (kept by DSF off the SD),
and a copy whose sha is not the manifest's is never used.
"""
import difflib
import hashlib
import os
import time

import fs_atomic
import install_log
import paths
import sd_integrity
import sd_manifest
import service_restart

FACTORY = os.path.join(os.path.dirname(os.path.abspath(__file__)), "factory")
LEGACY = "sys/workshop/legacy"
GUARD_FOLDER = "sys/workshop/macros/guard/"
HOOKS_FOLDER = "sys/workshop/hooks/"
HOOK_MARKER = "WORKSHOP hook="
MAX_BYTES = sd_integrity.MAX_BYTES
ABSENT = "absent"

_KIND_REASON = {
    "template": "a template is the person's after its first copy; it is created again only through the examples",
    "native-managed": "a native file of the board that the person owns; the workshop never rewrites it from here",
    "generated": "the service writes it at run time; it is regenerated by its generator, not copied",
    "expected-external": "nobody ships it: the person provides it",
}


class RestoreRefused(Exception):
    def __init__(self, code, reasons):
        super().__init__(code)
        self.code = code
        self.reasons = reasons


def _sha(data):
    return hashlib.sha256(data).hexdigest()


def protected(manifest=None):
    """{path: why} of the workshop-owned files that run in pause, cancel, homing, the laser guard or at start-up, directly or called by
    one that does. Derived from the manifest: the guard folder, the safety list, every file a native file calls through a hook, and
    (transitively) every file that one of those lists in used_by."""
    data = sd_manifest.load(manifest)
    owned = {e["path"]: e for e in data["files"] if e["kind"] == "workshop-owned"}
    why = {}
    for p in owned:
        if p.startswith(GUARD_FOLDER):
            why[p] = "laser or CNC guard"
        if p in sd_integrity.SAFETY:
            why[p] = "safety file (free jog failsafe / stall detection)"
    for e in data["files"]:
        if e["kind"] == "native-managed":
            for hook in e.get("hooks", []):
                # a hook is the file name ("zbedref.g") or, in the real manifest, the marker of a managed block
                # ("WORKSHOP hook=homez-tail"), whose target is sys/workshop/hooks/<name>.g
                target = hook[len(HOOK_MARKER):] + ".g" if hook.startswith(HOOK_MARKER) else hook
                for p in owned:
                    if p.rsplit("/", 1)[-1] == target and (target == hook or p.startswith(HOOKS_FOLDER)):
                        why.setdefault(p, "called from %s (runs at start-up, homing or in the daemon loop)" % e["path"])
    changed = True
    while changed:
        changed = False
        for p, e in owned.items():
            if p in why:
                continue
            for caller in e.get("used_by", []):
                if caller in why:
                    why[p] = "called by %s, which is protected" % caller
                    changed = True
                    break
    return why


def _read(route):
    """(bytes | None, problem | None) of a file for reading; a link or a folder is not a file."""
    try:
        if os.path.islink(route) or (os.path.lexists(route) and not os.path.isfile(route)):
            return None, "not_a_file"
        if not os.path.lexists(route):
            return None, ABSENT
        if os.path.getsize(route) > MAX_BYTES:
            return None, "not_a_file"
        with open(route, "rb") as f:
            return f.read(), None
    except OSError:
        return None, "not_a_file"


def _factory(entry, factory):
    data, problem = _read(os.path.join(factory, *entry["path"].split("/")))
    if data is None:
        return None, "factory_missing", "no factory copy of this file in the plugin (%s)" % problem
    if _sha(data) != entry["sha256"]:
        return None, "factory_mismatch", "the factory copy does not match the manifest: it is not used"
    return data, None, None


def _diff(current, new, path):
    a = current.decode("utf-8", "replace").splitlines(keepends=True) if current else []
    b = new.decode("utf-8", "replace").splitlines(keepends=True)
    return install_log.redact("".join(difflib.unified_diff(a, b, "current/" + path, "factory/" + path)))


def blockers(getters):
    return [{"code": "board_busy", "reason": str(r["message"]), "detail": r["code"]} for r in service_restart.blockers(getters)]


def preview(path, sd=None, manifest=None, factory=None, getters=None):
    """What restoring `path` would do. NEVER writes. `allowed` is false when `refusals` is not empty."""
    sd = sd or paths.SD
    factory = factory or FACTORY
    path = str(path or "")
    out = {"path": path, "read_only": True, "allowed": False, "refusals": [], "diff": "", "expected_sha": None}
    entry = sd_manifest.find(path, manifest)
    if entry is None:
        out["refusals"].append({"code": "not_in_manifest", "reason": "the file is not listed in the manifest of the workshop files"})
        return out
    out["kind"] = entry["kind"]
    out["plugin"] = entry.get("plugin")
    if entry["kind"] != "workshop-owned":
        out["refusals"].append({"code": "wrong_kind", "reason": _KIND_REASON[entry["kind"]]})
        return out
    why = protected(manifest).get(path)
    if why:
        out["refusals"].append({"code": "safety", "reason": why + ": it is restored only with the owner at the machine, never from here"})
    current, problem = _read(os.path.join(sd, *path.split("/")))
    if problem == "not_a_file":
        out["refusals"].append({"code": "not_a_file", "reason": "the path is a link, a folder or unreadable: nothing is replaced"})
    out["state"] = "deleted" if problem == ABSENT else ("ok" if current is not None and _sha(current) == entry["sha256"] else "edited")
    if out["state"] == "ok":
        out["refusals"].append({"code": "already_ok", "reason": "the file is already the factory one"})
    new, code, reason = _factory(entry, factory)
    if code:
        out["refusals"].append({"code": code, "reason": reason})
    if problem != "not_a_file":
        out["expected_sha"] = ABSENT if current is None else _sha(current)
        out["sha_current"] = None if current is None else _sha(current)
        if new is not None:
            out["diff"] = _diff(current, new, path)
    out["sha_factory"] = entry["sha256"]
    if getters is not None:
        out["refusals"].extend(blockers(getters))
    out["allowed"] = not out["refusals"]
    return out


def _backup_path(sd, path):
    rel = "%s/%s/%s" % (LEGACY, time.strftime("%Y%m%d"), path)
    if os.path.lexists(os.path.join(sd, *rel.split("/"))):
        rel += "." + time.strftime("%H%M%S")
    return rel


def _finish(run):
    """The log never breaks the answer: a failure of the table leaves run_id None."""
    try:
        return run.finish()
    except Exception:  # noqa: BLE001
        return None


def restore(path, expected_sha, getters, actor=None, sd=None, manifest=None, factory=None):
    """Restores `path` from the factory copy. Raises RestoreRefused (code, reasons) when it does not; returns the result dict.
    `expected_sha` must be the one of preview(): a file edited after the person looked is not replaced. `getters` is required: there
    is no way to restore without a reading of the state of the board."""
    sd = sd or paths.SD
    factory = factory or FACTORY
    actor = actor or {}
    plan = preview(path, sd, manifest, factory, getters)
    run = install_log.Run("integrity-restore", actor.get("user", ""), actor.get("role", ""), actor.get("device", ""), actor.get("via", "api"),
                          False, {plan["plugin"]: ""} if plan.get("plugin") else {})

    def refuse(code, reasons, backup=None):
        run.add(plan.get("plugin"), path, "failed", plan.get("kind"), code, sha_before=plan.get("sha_current"), backup_path=backup,
                error="; ".join(r["reason"] for r in reasons))
        _finish(run)
        raise RestoreRefused(code, reasons)

    if plan["refusals"]:
        refuse(plan["refusals"][0]["code"], plan["refusals"])
    if str(expected_sha or "") != plan["expected_sha"]:
        refuse("changed_since_preview", [{"code": "changed_since_preview", "reason": "the file changed after the preview: look at the new diff and ask again"}])
    entry = sd_manifest.find(path, manifest)
    route = os.path.join(sd, *path.split("/"))
    current, _ = _read(route)
    new, _c, _r = _factory(entry, factory)
    backup = None
    try:
        if current is not None:
            backup = _backup_path(sd, path)
            fs_atomic.write_bytes(os.path.join(sd, *backup.split("/")), current)
        again = blockers(getters)  # the state may have changed while the copy was made
        if again:
            refuse("board_busy", again, backup)
        fs_atomic.write_bytes(route, new)
        after, _p = _read(route)
        if after is None or _sha(after) != entry["sha256"]:
            raise OSError("the file written does not match the factory sha")
    except OSError as e:
        refuse("write_error", [{"code": "write_error", "reason": "could not write the file: %s" % e}], backup)
    run.add(plan.get("plugin"), path, "restored", "workshop-owned", "explicit_admin_request", sha_before=plan.get("sha_current"),
            sha_after=entry["sha256"], size_before=None if current is None else len(current), size_after=len(new), backup_path=backup, diff=plan["diff"])
    run_id = _finish(run)
    return {"restored": True, "path": path, "sha_before": plan.get("sha_current"), "sha_after": entry["sha256"], "backup_path": backup, "run_id": run_id}
