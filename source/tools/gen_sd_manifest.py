FACTORY_OUT = os.path.join(os.path.dirname(HERE), "dsf", "factory")
PLUGIN_JSON = os.path.join(os.path.dirname(HERE), "plugin.json")
STAGING = "sys/workshop/examples/"
CALL = re.compile(r'M98\s+P"(?:0:)?/?([^"]+)"', re.I)

