"""Builds dsf/sd_manifest.json (the single source of truth of the SD files of the workshop plugins, SD-LAYOUT.md B.4).

Read only on the zips: it opens the released plugin zips (the `sd/` tree of each one is what DSF puts on the SD), takes the
sha256 of every file and writes the manifest. The files that no zip ships (native files with a workshop hook, files the
service generates, files the person provides) are the curated tables below.

    python tools/gen_sd_manifest.py --zips C:/.../TallerPlugins/dist/3.6 [--out dsf/sd_manifest.json] [--factory dsf/factory] [--plugin-json plugin.json]

Besides the manifest it lays out the FACTORY tree that dsf/sd_restore.py restores from (dsf/factory/<path>: the bytes of every
workshop-owned file, so the sha of each one is the manifest's) and lists it in plugin.json dsfFiles (tools/factory_tree.py).
`--no-factory` writes the manifest alone. It never touches a machine and never writes anywhere but --out, --factory and --plugin-json.
"""
