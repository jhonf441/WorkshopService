def sha(data):
    return hashlib.sha256(data).hexdigest()


def read_zips(folder):
    """{plugin: {"version": v, "files": {sd path: bytes}}}"""
    out = {}
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".zip"):
            continue
        with zipfile.ZipFile(os.path.join(folder, name)) as z:
            pj = json.loads(z.read("plugin.json"))
            files = {n[3:]: z.read(n) for n in z.namelist() if n.startswith("sd/") and not n.endswith("/")}
            declared = sorted(pj.get("sdFiles") or [])
            if declared and declared != sorted(files):
                raise SystemExit("%s: sdFiles of plugin.json differ from the sd/ folder" % name)
            if files:
                out[pj["id"]] = {"version": pj["version"], "files": files}
    return out


def build(zips):
    entries, calls = [], {}
    for pid, info in zips.items():
        for rel, data in sorted(info["files"].items()):
            if rel.startswith(STAGING + pid + "/"):
                dest = rel[len(STAGING + pid + "/"):]
                e = {"path": dest, "kind": "template", "plugin": pid, "stage": rel, "sha256": sha(data),
                     "create": "if-missing-and-never-created", "overwrite": "never"}
            else:
                e = {"path": rel, "kind": "workshop-owned", "plugin": pid, "sha256": sha(data), "overwrite": "always"}
            entries.append(e)
            for line in data.decode("utf-8", "replace").splitlines():
                if line.lstrip().startswith(";"):
                    continue
                for m in CALL.finditer(line):
                    calls.setdefault(m.group(1), set()).add(e["path"])
    for e in entries:
        users = sorted(calls.get(e["path"], set()) - {e["path"]})
        e["used_by"] = [e["plugin"]] + users
    by_path = {e["path"]: e for e in entries}

    def add(e, merge):
        """A path that a zip already ships as a template keeps that kind (the copy becomes the person's) and only gains the extra facts."""
        old = by_path.get(e["path"])
        if old is None:
            entries.append(e)
            by_path[e["path"]] = e
        elif old["kind"] == "template":
            old.update(merge)
        else:
            raise SystemExit("a path in two entries: %s" % e["path"])

    for path, plugins, hooks in NATIVE:
        add({"path": path, "kind": "native-managed", "plugin": plugins[0], "used_by": plugins, "hooks": hooks, "mode": "read-only"},
            {"native": True, "hooks": hooks})
    for path, gen, mark, users in GENERATED:
        add({"path": path, "kind": "generated", "plugin": "WorkshopService", "generator": gen, "mark": mark, "used_by": users},
            {"generator": gen, "mark": mark})
    for path, users, breaks in EXTERNAL:
        add({"path": path, "kind": "expected-external", "plugin": users[0].split(":")[0], "provider": "user", "used_by": users,
             "breaks_if_missing": breaks}, {"breaks_if_missing": breaks})
    entries.sort(key=lambda e: e["path"])
    return {"schema": 1, "plugins": {p: i["version"] for p, i in sorted(zips.items())}, "files": entries}


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--zips", required=True)
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--factory", default=FACTORY_OUT)
    ap.add_argument("--plugin-json", default=PLUGIN_JSON)
    ap.add_argument("--no-factory", action="store_true")
    a = ap.parse_args(argv)
    zips = read_zips(a.zips)
    manifest = build(zips)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=1, sort_keys=True)
        f.write("\n")
    if not a.no_factory:
        data = {e["path"]: zips[e["plugin"]]["files"][e["path"]] for e in manifest["files"] if e["kind"] == "workshop-owned"}
        paths = factory_tree.write(data, a.factory)
        changed = factory_tree.sync_plugin_json(a.plugin_json, paths)
        print("factory tree %s: %d files, %s dsfFiles %s" % (a.factory, len(paths), a.plugin_json, "updated" if changed else "already right"))
    kinds = {}
    for e in manifest["files"]:
        kinds[e["kind"]] = kinds.get(e["kind"], 0) + 1
    print("wrote %s: %d files %s" % (a.out, len(manifest["files"]), kinds))
    return 0


if __name__ == "__main__":
    sys.exit(main())
