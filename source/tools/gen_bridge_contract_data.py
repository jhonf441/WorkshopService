#!/usr/bin/env python3
"""Generates dwc36/bridge-contract-data.js, the data of the contract viewer in the bridge card, from the contract itself:

    bridge/contract/state.schema.json    every key of the state file: type, required or optional
    bridge/contract/action.schema.json   the action file
    bridge/contract/viewer.json          the curated part: the channels of CONTRACT.md section 1, the key rules (each tagged with its section),
                                         and a description of every state key in Spanish and English

    python tools/gen_bridge_contract_data.py            write the module
    python tools/gen_bridge_contract_data.py --check    exit 1 if the module on disk is not what the sources generate (the guard test runs this)
    python tools/gen_bridge_contract_data.py --paths    list the key paths of the state schema (to write viewer.json)

The page cannot read CONTRACT.md or the schemas at run time and webpack cannot import files outside dwc36, so the viewer reads this module. The
output is deterministic (sorted by the order of the schema, no dates), so the guard can compare bytes: a change of a schema that is not followed
by a regeneration fails `bridge/tests/test_viewer_data.py`, and a key without a description in viewer.json fails it too. The viewer cannot drift
from the contract.
"""
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CONTRACT = os.path.join(ROOT, "bridge", "contract")
OUT = os.path.join(ROOT, "dwc36", "bridge-contract-data.js")
SOURCES = ("state.schema.json", "action.schema.json", "viewer.json")


def load(name):
    with open(os.path.join(CONTRACT, name), encoding="utf-8") as fh:
        return json.load(fh)


def as_list(t):
    if t is None:
        return []
    return list(t) if isinstance(t, list) else [t]


def flatten(schema, prefix=""):
    """[{path, types, required}] for every key of an object schema, depth first, in the order of its `properties`. An array of objects
    gives the array itself ("clients") and its elements' keys ("clients[].id"); `required` is relative to the object that holds the key."""
    out = []
    required = set(schema.get("required") or [])
    for key, sub in (schema.get("properties") or {}).items():
        path = prefix + key
        types = as_list(sub.get("type"))
        out.append({"path": path, "types": types, "required": key in required})
        if "object" in types and sub.get("properties"):
            out += flatten(sub, path + ".")
        if "array" in types and isinstance(sub.get("items"), dict) and sub["items"].get("properties"):
            out += flatten(sub["items"], path + "[].")
    return out


def sha(names):
    h = hashlib.sha256()
    for n in names:
        with open(os.path.join(CONTRACT, n), "rb") as fh:
            h.update(fh.read().replace(b"\r\n", b"\n"))
    return h.hexdigest()


def build():
    state, action, view = load("state.schema.json"), load("action.schema.json"), load("viewer.json")
    keys = flatten(state)
    texts = view.get("keys") or {}
    missing = [k["path"] for k in keys if not (texts.get(k["path"]) or {}).get("en") or not (texts.get(k["path"]) or {}).get("es")]
    stale = sorted(set(texts) - {k["path"] for k in keys})
    if missing or stale:
        raise SystemExit("viewer.json: keys without a description (en and es): %s; descriptions of keys that no longer exist: %s" % (missing, stale))
    for k in keys:
        k["en"], k["es"] = texts[k["path"]]["en"], texts[k["path"]]["es"]
    data = {
        "sources": sha(SOURCES),
        "contract": view["contract"],
        "schemas": state["properties"]["schema"]["enum"],
        "stateTitle": state.get("title"),
        "stateKeys": keys,
        "actionKeys": flatten(action),
        "channels": view["channels"],
        "rules": view["rules"],
    }
    parts = ["'use strict'\n\n// GENERATED by tools/gen_bridge_contract_data.py from bridge/contract/*.schema.json and viewer.json. Do not edit: change the sources and\n"
             "// run the script; bridge/tests/test_viewer_data.py fails when this file is out of date. Data of the contract viewer (BridgeContractDialog.vue).\n"]
    for name, value in (("SOURCES_SHA256", data["sources"]), ("CONTRACT_VERSION", data["contract"]), ("KNOWN_SCHEMAS", data["schemas"]),
                        ("STATE_KEYS", data["stateKeys"]), ("ACTION_KEYS", data["actionKeys"]), ("CHANNELS", data["channels"]), ("RULES", data["rules"])):
        parts.append("\nexport const %s = %s\n" % (name, json.dumps(value, indent="\t", ensure_ascii=False)))
    return "".join(parts)


def main(argv):
    arg = argv[1] if len(argv) > 1 else ""
    if arg == "--paths":
        for k in flatten(load("state.schema.json")):
            print("%-34s %-22s %s" % (k["path"], "/".join(k["types"]), "required" if k["required"] else "optional"))
        return 0
    text = build()
    if arg == "--check":
        try:
            with open(OUT, encoding="utf-8", newline="") as fh:
                have = fh.read().replace("\r\n", "\n")
        except OSError:
            have = None
        if have != text:
            print("dwc36/bridge-contract-data.js is out of date: run python tools/gen_bridge_contract_data.py", file=sys.stderr)
            return 1
        print("bridge-contract-data.js is up to date")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
